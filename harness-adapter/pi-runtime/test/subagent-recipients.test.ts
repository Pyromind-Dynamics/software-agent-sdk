import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, writeFile, realpath, rm } from "node:fs/promises";
import { join } from "node:path";
import test from "node:test";
import { SessionManager, type AgentSession } from "@earendil-works/pi-coding-agent";
import { SubagentRecipients } from "../src/subagent-recipients.js";

test("same-role recipients survive restart and address only their original native session", async t => {
  const root = await realpath(await mkdtemp("/tmp/pi-recipients-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const stateRoot = join(root, "subagents"), sessions = join(stateRoot, "sessions");
  await mkdir(sessions, { recursive: true });
  const parentFile = join(root, "parent.jsonl");
  const header = (id: string) => JSON.stringify({type: "session", version: 3, id, timestamp: new Date().toISOString(), cwd: root}) + "\n";
  await writeFile(parentFile, header("parent"));
  const childFiles = [join(sessions, "one.jsonl"), join(sessions, "two.jsonl")];
  await Promise.all(childFiles.map((path, i) => writeFile(path, header(`child-${i}`))));
  let manager = SessionManager.open(parentFile);
  const calls: any[] = [];
  const rpc = async (...args: any[]) => { calls.push(args); return { details: {state: "queued"} }; };
  const session = () => ({sessionId: "parent", sessionManager: manager} as unknown as AgentSession);
  let recipients = new SubagentRecipients(stateRoot, session(), rpc);
  const origins = childFiles.map((file, i) => recipients.origin(`child-${i}`, file));
  assert.notEqual(origins[0].subagent_id, origins[1].subagent_id);
  const saveRun = async (id: string, index: number, state: string, startedAt: number) => {
    const dir = join(stateRoot, "async-subagent-runs", id);
    await mkdir(dir, {recursive: true});
    await writeFile(join(dir, "status.json"), JSON.stringify({lifecycleArtifactVersion: 3, runId: id, sessionId: parentFile, state, startedAt, steps: [{agent:"worker", index: 0, sessionFile: childFiles[index], status: state}]}));
  };
  await saveRun("run-one", 0, "running", 1);
  await saveRun("run-two", 1, "complete", 2);
  const notice = (i: number, run_id: string) => ({run_id, content: "任务完成：引号 \" 与中文", trigger_turn: true, details: {correlation: {...origins[i], conversation_id: "conversation", version: 1, source:"agent", task_kind:"workflow_run"}}});
  assert.equal((await recipients.notify(notice(0, "task-one"))).accepted, true);
  assert.equal(calls[0][0], "steer");
  assert.equal(calls[0][1].id, "run-one");
  assert.equal(calls[0][1].mode, "follow_up");
  assert.equal((await recipients.notify(notice(1, "task-two"))).accepted, true);
  assert.equal(calls[1][0], "resume");
  assert.equal(calls[1][1].id, "run-two");
  assert.equal(calls[1][1].index, 0);
  manager = SessionManager.open(parentFile);
  recipients = new SubagentRecipients(stateRoot, session(), rpc);
  assert.deepEqual(recipients.origin("child-0", childFiles[0]), origins[0]);
  assert.equal((await recipients.notify(notice(0, "task-one"))).duplicate, true);
  assert.equal(calls.length, 2);
  await saveRun("resumed-one", 0, "running", 3);
  await recipients.notify(notice(0, "another-task"));
  assert.equal(calls[2][1].id, "resumed-one");
  await saveRun("resumed-one", 0, "stopped", 3);
  assert.equal((await recipients.notify(notice(0, "stopped-task"))).accepted, false);
  assert.equal(calls.length, 3);
  await assert.rejects(recipients.notify({...notice(0, "forged"), details:{correlation: {type:"main"}}}), /return address/);
  const other = join(root, "foreign.jsonl");
  await writeFile(other, header("foreign"));
  assert.throws(() => recipients.origin("foreign", other), /another conversation/);
  assert.throws(() => recipients.origin("wrong-session", childFiles[0]), /identity mismatch/);
  assert.ok((await readFile(parentFile, "utf8")).includes("pyromind.subagent.delivery"));
});
