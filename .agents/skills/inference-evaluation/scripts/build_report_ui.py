#!/usr/bin/env python3
"""Build the browser-ready evaluation report UI assets."""

from __future__ import annotations

import argparse
from pathlib import Path


ROOT = Path(__file__).parent
SOURCE = ROOT / "report_ui"
JAVASCRIPT_SOURCES = (
    SOURCE / "annotation-store.js",
    SOURCE / "case-source.js",
    SOURCE / "renderer.js",
    SOURCE / "index.js",
)
JAVASCRIPT_OUTPUT = ROOT / "evaluation_report.js"
CSS_SOURCE = SOURCE / "styles.css"
CSS_OUTPUT = ROOT / "evaluation_report.css"
GENERATED_HEADER = "/* Generated by build_report_ui.py; do not edit directly. */\n"


def javascript_bundle() -> str:
    modules = [path.read_text(encoding="utf-8").rstrip() for path in JAVASCRIPT_SOURCES]
    return GENERATED_HEADER + "\n\n".join(modules) + "\n"


def css_bundle() -> str:
    return GENERATED_HEADER + CSS_SOURCE.read_text(encoding="utf-8").lstrip()


def check() -> bool:
    return (
        JAVASCRIPT_OUTPUT.is_file()
        and CSS_OUTPUT.is_file()
        and JAVASCRIPT_OUTPUT.read_text(encoding="utf-8") == javascript_bundle()
        and CSS_OUTPUT.read_text(encoding="utf-8") == css_bundle()
    )


def build() -> None:
    JAVASCRIPT_OUTPUT.write_text(javascript_bundle(), encoding="utf-8")
    CSS_OUTPUT.write_text(css_bundle(), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        if not check():
            raise SystemExit("evaluation report UI bundle is stale")
        return
    build()


if __name__ == "__main__":
    main()
